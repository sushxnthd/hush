#!/usr/bin/env python3
"""Independent, fail-closed replay of HUSH-077's sanitised test traces.

The trace is generated by the fixture; it is not an externally authenticated
provider log and cannot establish remote provider clock or idempotency.
"""
import json
import re
import sys

PATTERN = re.compile(r"HUSH077_TRACE (\{[^\n]+\})")
EXPECTED = {
    False: [
        {"event": "provider_http_effect", "ordinal": 1},
        {"event": "broker_sigkill"},
        {"event": "broker_restart"},
        {"event": "provider_http_effect", "ordinal": 2},
        {"event": "retry_receipt"},
    ],
    True: [
        {"event": "provider_http_effect", "ordinal": 1},
        {"event": "broker_sigkill"},
        {"event": "broker_restart"},
        {"event": "durable_revoke"},
    ],
}


def replay(text):
    traces = [json.loads(m.group(1)) for m in PATTERN.finditer(text)]
    if len(traces) != 2:
        raise ValueError(f"Expected exactly two HUSH-077 traces; got {len(traces)}")
    seen = set()
    for t in traces:
        revoked = t.get("revoked")
        if type(revoked) is not bool or revoked in seen:
            raise ValueError("Missing or duplicate control arm")
        seen.add(revoked)
        if t.get("events") != EXPECTED[revoked]:
            raise ValueError("Crash/restart/effect event order mismatch")
        if t.get("effectCount") != (1 if revoked else 2):
            raise ValueError("Effect count mismatch")
        if t.get("firstReceiptRecovered") is not False:
            raise ValueError("First receipt incorrectly recovered")
        if t.get("postRestartReceiptCount") != (0 if revoked else 1):
            raise ValueError("Receipt count mismatch")
        if set(t) != {
            "effectCount", "revoked", "firstReceiptRecovered",
            "postRestartReceiptCount", "events"
        }:
            raise ValueError("Unexpected or sensitive trace field")
    return {"experiment": "HUSH-077", "replayed": 2,
            "crash_retry_duplicate": True, "revoked_retry_blocked": True,
            "provider_independently_attested": False}


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: python hush_077_independent_replay.py <test-log>")
    with open(sys.argv[1], encoding="utf-8") as f:
        print(json.dumps(replay(f.read()), sort_keys=True))
